const PROXY_URL = "https://provere-proxy.imsalper.workers.dev/";

async function callGeminiVision(base64Data, mimeType, prompt) {
  const models = [
    'gemini-flash-lite-latest',
    'gemini-3.5-flash-lite',
    'gemini-3.5-flash',
    'gemini-flash-latest',
    'gemini-3.8-flash'
  ];

  const cleanBase64 = base64Data.includes(',') ? base64Data.split(',')[1] : base64Data;
  const actualMime = (mimeType && mimeType.includes('png')) ? 'image/png' : 'image/jpeg';
  let lastErr = null;

  for (const model of models) {
    try {
      const body = {
        model: model,
        contents: [
          {
            role: "user",
            parts: [
              { text: prompt },
              {
                inline_data: {
                  mime_type: actualMime,
                  data: cleanBase64
                }
              }
            ]
          }
        ],
        generationConfig: {
          maxOutputTokens: 2048,
          temperature: 0.1
        }
      };

      const res = await fetch(PROXY_URL, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body)
      });

      if (!res.ok) {
        const errText = await res.text();
        console.warn(`[Provere Failover] ${model} (${res.status}), sıradaki modele geçiliyor...`);
        lastErr = new Error(`${model} (${res.status}): ${errText.slice(0, 100)}`);
        continue;
      }

      const data = await res.json();
      const candidate = (data.candidates && data.candidates[0]) || {};
      const text = ((candidate.content && candidate.content.parts) || []).map(p => p.text || '').join('\n');
      if (!text) {
        lastErr = new Error("Model boş yanıt döndürdü.");
        continue;
      }
      return text;
    } catch (err) {
      console.warn(`[Provere Failover] ${model} ağ hatası:`, err);
      lastErr = err;
      continue;
    }
  }

  throw lastErr || new Error("Adli bilişim yapay zeka servisine erişilemedi.");
}

