// Select Mode (Photo vs Video)
function selectMode(mode) {
  currentMode = mode;
  document.getElementById('mode-photo-btn').classList.toggle('active', mode === 'photo');
  document.getElementById('mode-video-btn').classList.toggle('active', mode === 'video');

  // Trigger appropriate native file picker immediately
  triggerFilePicker();
}

function triggerFilePicker() {
  if (currentMode === 'photo') {
    document.getElementById('input-photo').click();
  } else {
    document.getElementById('input-video').click();
  }
}

// Handle File Selected
function handleFileSelected(e, mode) {
  const file = e.target.files[0];
  if (!file) return;

  selectedFile = file;
  const previewCard = document.getElementById('preview-card');
  const uploadPlaceholder = document.getElementById('upload-placeholder');
  const previewContainer = document.getElementById('media-preview-container');
  const imgPreview = document.getElementById('img-preview');
  const videoPreview = document.getElementById('video-preview');
  const infoText = document.getElementById('media-info-text');
  const checkBtn = document.getElementById('btn-control');
  const resultCard = document.getElementById('result-card');

  resultCard.style.display = 'none';
  uploadPlaceholder.style.display = 'none';
  previewContainer.style.display = 'flex';
  previewCard.classList.add('has-file');

  const sizeMb = (file.size / (1024 * 1024)).toFixed(2);
  infoText.textContent = `${file.name} (${sizeMb} MB)`;

  if (mode === 'photo') {
    videoPreview.style.display = 'none';
    imgPreview.style.display = 'block';

    const reader = new FileReader();
    reader.onload = (event) => {
      imgPreview.src = event.target.result;
      selectedFileBase64 = event.target.result;
      checkBtn.disabled = false;
    };
    reader.readAsDataURL(file);
  } else {
    imgPreview.style.display = 'none';
    videoPreview.style.display = 'block';

    const videoUrl = URL.createObjectURL(file);
    videoPreview.src = videoUrl;
    selectedFileBase64 = null; // Videos use object URL & canvas sampling
    checkBtn.disabled = false;
  }
}

// Drag & Drop Support
function setupDragAndDrop() {
  const card = document.getElementById('preview-card');

  ['dragenter', 'dragover'].forEach(name => {
    card.addEventListener(name, (e) => {
      e.preventDefault();
      card.style.borderColor = 'var(--neon-cyan)';
    });
  });

  ['dragleave', 'drop'].forEach(name => {
    card.addEventListener(name, (e) => {
      e.preventDefault();
      card.style.borderColor = '';
    });
  });

  card.addEventListener('drop', (e) => {
    const file = e.dataTransfer.files[0];
    if (!file) return;

    if (file.type.startsWith('image/')) {
      currentMode = 'photo';
      selectMode('photo');
      handleFileSelected({ target: { files: [file] } }, 'photo');
    } else if (file.type.startsWith('video/')) {
      currentMode = 'video';
      selectMode('video');
      handleFileSelected({ target: { files: [file] } }, 'video');
    }
  });
}

