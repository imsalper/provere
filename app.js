// Universal Memory-Safe Image Optimizer (Downscales 48MP iPhone photos to crisp 1600px JPEG)
async function prepareImageForAnalysis(file, imgElement) {
  return new Promise((resolve) => {
    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.onload = () => {
      const maxDim = 1600;
      let width = img.naturalWidth || img.width;
      let height = img.naturalHeight || img.height;

      if (width > maxDim || height > maxDim) {
        if (width > height) {
          height = Math.round((height * maxDim) / width);
          width = maxDim;
        } else {
          width = Math.round((width * maxDim) / height);
          height = maxDim;
        }
      }

      const canvas = document.createElement('canvas');
      canvas.width = Math.max(width, 100);
      canvas.height = Math.max(height, 100);
      const ctx = canvas.getContext('2d', { willReadFrequently: true });
      ctx.imageSmoothingEnabled = true;
      ctx.imageSmoothingQuality = 'high';
      ctx.drawImage(img, 0, 0, width, height);

      // Perform fast localized variance check (Laplacian grain analysis)
      let noiseScore = 0;
      try {
        const sampleSize = Math.min(200, width);
        const imgData = ctx.getImageData(0, 0, sampleSize, sampleSize);
        const data = imgData.data;
        let diffSum = 0;
        for (let i = 0; i < data.length - 8; i += 4) {
          diffSum += Math.abs(data[i] - data[i + 4]);
        }
        noiseScore = (diffSum / (sampleSize * sampleSize)).toFixed(1);
      } catch (err) {
        // Ignore cross-origin context restrictions
      }

      const optimized = canvas.toDataURL('image/jpeg', 0.86);
      resolve({
        base64: optimized,
        mimeType: 'image/jpeg',
        noiseScore: parseFloat(noiseScore) || 0,
        width,
        height
      });
    };

    img.onerror = () => {
      // Fallback if Image constructor fails on exotic format
      const reader = new FileReader();
      reader.onload = () => resolve({ base64: reader.result, mimeType: file.type || 'image/jpeg', noiseScore: 0 });
      reader.onerror = () => resolve({ base64: null, mimeType: 'image/jpeg', noiseScore: 0 });
      reader.readAsDataURL(file);
    };

    img.src = selectedFileObjectUrl;
  });
}

// Enterprise-Grade Forensic Container & EXIF Hardware Analyzer
// Detects: Physical camera sensors (Apple, Samsung, Sony, Canon), lens metadata, exposure, ISO, GPS,
// and AI generation markers (Stable Diffusion/ComfyUI prompts embedded in PNG chunks or JPEG comments).
async function analyzeForensicContainer(file) {
  if (!file) return { isVerifiedHardware: false };

  const result = {
    isVerifiedHardware: false,
    cameraMake: null,
    cameraModel: null,
    lensModel: null,
    fNumber: null,
    exposureTime: null,
    iso: null,
    dateTime: null,
    gps: null,
    software: null,
    isAiMetadataTag: false,
    isHeicContainer: false,
    format: 'unknown'
  };

  try {
    const sliceSize = Math.min(file.size, 192 * 1024); // First 192KB contains all EXIF/ISOBMFF atoms
    const buffer = await file.slice(0, sliceSize).arrayBuffer();
    const view = new DataView(buffer);
    const bytes = new Uint8Array(buffer);

    // 1. Check for HEIC / HEIF / Apple QuickTime ISOBMFF container
    // Magic: bytes 4-8 contain 'ftyp' followed by 'heic', 'mif1', 'msf1', 'isom'
    let asciiHeader = "";
    for (let k = 0; k < Math.min(256, bytes.length); k++) {
      asciiHeader += String.fromCharCode(bytes[k]);
    }

    if (asciiHeader.includes('ftypheic') || asciiHeader.includes('ftypmif1') || asciiHeader.includes('ftypmsf1') || asciiHeader.includes('ftypisom')) {
      result.isHeicContainer = true;
      result.format = 'HEIC/HEIF';

      // Check for Apple hardware tags inside ISOBMFF metadata strings
      let bufferText = "";
      for (let k = 0; k < Math.min(32768, bytes.length); k++) {
        const c = bytes[k];
        if (c >= 32 && c <= 126) bufferText += String.fromCharCode(c);
        else bufferText += " ";
      }

      if (bufferText.includes("Apple") || bufferText.includes("iPhone")) {
        result.cameraMake = "Apple";
        const match = bufferText.match(/iPhone\s*(\d+[\s\w]*)/i);
        result.cameraModel = match ? match[0].trim() : "iPhone";
      }
    }

    // 2. Check for PNG format & Stable Diffusion / ComfyUI metadata
    if (bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4E && bytes[3] === 0x47) {
      result.format = 'PNG';
      let pngText = "";
      for (let k = 0; k < bytes.length; k++) {
        const c = bytes[k];
        if (c >= 32 && c <= 126) pngText += String.fromCharCode(c);
      }
      if (pngText.includes("parameters") && (pngText.includes("Steps:") || pngText.includes("Sampler:") || pngText.includes("CFG scale:"))) {
        result.isAiMetadataTag = true;
      }
    }

    // 3. Check for JPEG EXIF (0xFFD8)
    if (view.getUint16(0, false) === 0xFFD8) {
      result.format = 'JPEG';
      let offset = 2;
      const length = view.byteLength;

      while (offset < length - 4) {
        if (view.getUint8(offset) !== 0xFF) break;
        const marker = view.getUint8(offset + 1);

        // APP1 (EXIF Marker)
        if (marker === 0xE1) {
          const exifOffset = offset + 4;
          if (view.getUint32(exifOffset, false) === 0x45786966) { // "Exif"
            const tiffOffset = exifOffset + 6;
            const bigEndian = view.getUint16(tiffOffset, false) === 0x4D4D;
            const ifdOffset = view.getUint32(tiffOffset + 4, bigEndian);

            let cur = tiffOffset + ifdOffset;
            const entries = view.getUint16(cur, bigEndian);
            cur += 2;
            let subExifOffset = null;
            let gpsOffset = null;

            const readAscii = (valOffset, count) => {
              let str = '';
              const start = tiffOffset + valOffset;
              for (let k = 0; k < count - 1; k++) {
                if (start + k >= length) break;
                const charCode = view.getUint8(start + k);
                if (charCode === 0) break;
                str += String.fromCharCode(charCode);
              }
              return str.trim();
            };

            for (let i = 0; i < entries; i++) {
              const entryPos = cur + i * 12;
              if (entryPos + 12 > length) break;

              const tag = view.getUint16(entryPos, bigEndian);
              const type = view.getUint16(entryPos + 2, bigEndian);
              const count = view.getUint32(entryPos + 4, bigEndian);
              const valOffset = view.getUint32(entryPos + 8, bigEndian);

              if (tag === 0x010F && type === 2) {
                result.cameraMake = readAscii(valOffset, count);
              } else if (tag === 0x0110 && type === 2) {
                result.cameraModel = readAscii(valOffset, count);
              } else if (tag === 0x0131 && type === 2) {
                result.software = readAscii(valOffset, count);
              } else if (tag === 0x8769) {
                subExifOffset = valOffset; // SubIFD
              } else if (tag === 0x8825) {
                gpsOffset = valOffset; // GPS IFD
              }
            }

            // SubIFD (Optics, Exposure, ISO, Lens)
            if (subExifOffset && tiffOffset + subExifOffset < length) {
              const subCur = tiffOffset + subExifOffset;
              const subEntries = view.getUint16(subCur, bigEndian);
              for (let s = 0; s < subEntries; s++) {
                const sPos = subCur + 2 + s * 12;
                if (sPos + 12 > length) break;

                const sTag = view.getUint16(sPos, bigEndian);
                const sType = view.getUint16(sPos + 2, bigEndian);
                const sCount = view.getUint32(sPos + 4, bigEndian);
                const sVal = view.getUint32(sPos + 8, bigEndian);

                if (sTag === 0x829D) { // FNumber
                  const fnO = tiffOffset + sVal;
                  if (fnO + 8 <= length) {
                    const num = view.getUint32(fnO, bigEndian);
                    const den = view.getUint32(fnO + 4, bigEndian);
                    if (den > 0) result.fNumber = `f/${(num / den).toFixed(1)}`;
                  }
                } else if (sTag === 0x829A) { // ExposureTime
                  const expO = tiffOffset + sVal;
                  if (expO + 8 <= length) {
                    const num = view.getUint32(expO, bigEndian);
                    const den = view.getUint32(expO + 4, bigEndian);
                    if (den > 0 && num > 0) result.exposureTime = num < den ? `1/${Math.round(den / num)}s` : `${(num / den).toFixed(1)}s`;
                  }
                } else if (sTag === 0x8827) { // ISO
                  result.iso = `ISO ${sVal}`;
                } else if (sTag === 0xA434 && sType === 2) { // LensModel
                  result.lensModel = readAscii(sVal, sCount);
                }
              }
            }

            // GPS IFD
            if (gpsOffset && tiffOffset + gpsOffset < length) {
              const gpsCur = tiffOffset + gpsOffset;
              const gpsEntries = view.getUint16(gpsCur, bigEndian);
              let latRef = 'N', lonRef = 'E';
              let latVal = null, lonVal = null;

              const readCoord = (valOffset) => {
                const o = tiffOffset + valOffset;
                if (o + 24 > length) return null;
                const d1 = view.getUint32(o, bigEndian), d2 = view.getUint32(o + 4, bigEndian);
                const m1 = view.getUint32(o + 8, bigEndian), m2 = view.getUint32(o + 12, bigEndian);
                const s1 = view.getUint32(o + 16, bigEndian), s2 = view.getUint32(o + 20, bigEndian);
                if (d2 === 0 || m2 === 0 || s2 === 0) return null;
                return (d1 / d2) + ((m1 / m2) / 60) + ((s1 / s2) / 3600);
              };

              for (let j = 0; j < gpsEntries; j++) {
                const gPos = gpsCur + 2 + j * 12;
                if (gPos + 12 > length) break;
                const gTag = view.getUint16(gPos, bigEndian);
                if (gTag === 1) latRef = String.fromCharCode(view.getUint8(gPos + 8));
                else if (gTag === 2) latVal = readCoord(view.getUint32(gPos + 8, bigEndian));
                else if (gTag === 3) lonRef = String.fromCharCode(view.getUint8(gPos + 8));
                else if (gTag === 4) lonVal = readCoord(view.getUint32(gPos + 8, bigEndian));
              }

              if (latVal !== null && lonVal !== null) {
                if (latRef === 'S') latVal = -latVal;
                if (lonRef === 'W') lonVal = -lonVal;
                result.gps = { latitude: latVal, longitude: lonVal, isExifGps: true };
              }
            }

            // Sadece gerçek fiziksel kamera optiği (diyafram ve enstantane) mevcutsa donanım doğrulaması ver
            if (result.fNumber && result.exposureTime && (result.cameraMake || result.iso)) {
              result.isVerifiedHardware = true;
            }
          }
        }
        offset += 2 + view.getUint16(offset + 2, false);
      }
    }
  } catch (err) {
    console.warn("Adli metadata okuma:", err);
  }

  return result;
}

