// Render Analysis Result & Explainable AI Breakdown
function renderRealVerificationResult(data) {
  const resultCard = document.getElementById('result-card');
  const scoreVal = document.getElementById('score-val');
  const meterCircleBar = document.getElementById('meter-circle-bar');
  const verdictWrapper = document.getElementById('verdict-wrapper');
  const verdictTitle = document.getElementById('verdict-title');
  const verdictBadge = document.getElementById('verdict-badge');
  const signalsList = document.getElementById('signals-list');

  const prob = Math.min(100, Math.max(0, parseInt(data.ai_probability, 10) || 5));
  const isAi = data.verdict_type === 'ai' || prob >= 50;

  // SVG Meter (Circumference = ~377)
  const circumference = 377;
  const offset = circumference - (circumference * prob / 100);
  meterCircleBar.style.strokeDashoffset = offset;
  meterCircleBar.style.stroke = isAi ? 'var(--neon-red)' : 'var(--neon-green)';

  scoreVal.textContent = `${prob}%`;
  scoreVal.style.color = isAi ? 'var(--neon-red)' : 'var(--neon-green)';

  verdictWrapper.className = isAi ? 'is-ai' : 'is-real';
  verdictTitle.textContent = data.headline || (isAi ? "Yapay Zeka Sentezi (Sentetik Model)" : "Gerçek / Doğal Medya");
  verdictBadge.textContent = data.badge || (isAi ? "SENTETİK (AI)" : "GERÇEK MEDYA");

  // Signals
  const signals = Array.isArray(data.signals) ? data.signals : [];
  signalsList.innerHTML = signals.map(sig => `
    <div class="signal-item">
      <span class="signal-icon">${isAi ? '⚠️' : '✅'}</span>
      <span>${escapeHtml(sig)}</span>
    </div>
  `).join('');

  // 3. "Neden Bu Sonuç?" (Explainable AI / Breakdown) Paneli
  renderBreakdownPanel(data);

  // 5. Konum & GPS Kutusu (Sahte/Mock sonuç verilmez, dürüst doğrulama)
  renderLocationBox(data);

  resultCard.style.display = 'flex';
  resultCard.scrollIntoView({ behavior: 'smooth' });
}

